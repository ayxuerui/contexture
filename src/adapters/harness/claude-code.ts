import path from 'node:path';
import type { HarnessGenerationAdapter, PermissionConfigInput } from '../types.js';

/**
 * The reference harness-generation adapter. Claude Code loads `@path`
 * references in its memory files, so the generated entry file's whole job
 * is one `@AGENTS.md` line — no convention text is duplicated here, only
 * imported (harness-portability spec's "entry file only imports" rule).
 */

/** Store-relative — where the generated write-gate hook script lands. */
const HOOK_TARGET_PATH = '.claude/hooks/claude-code-write-gate.sh';

/**
 * Claude Code's own placeholder for the root of the project the session
 * opened. The harness expands it when the hook fires, not when this config
 * is written, which is what lets the generated file be byte-identical on
 * every machine and therefore safe to commit (reference-the-hook-by-project-dir).
 *
 * Held as a literal and joined with '/' rather than `path.join`: this is a
 * harness-interpreted token that merely looks like a path, and `path.join`
 * on Windows would backslash it into something Claude Code no longer
 * recognizes. `HOOK_TARGET_PATH` above is forward-slashed for the same reason.
 */
const PROJECT_DIR_PLACEHOLDER = '${CLAUDE_PROJECT_DIR}';

export const claudeCodeHarnessAdapter: HarnessGenerationAdapter = {
  id: 'claude-code',
  kind: 'harness-generation',
  interfaceVersion: 2,
  entryFileName: 'CLAUDE.md',
  skillsDir: '.claude/skills/',

  render(agentsMdPath: string): string[] {
    return [`@${path.basename(agentsMdPath)}`];
  },

  permissionConfig: {
    path: '.claude/settings.json',

    hookFile: {
      templateFileName: 'claude-code-write-gate.sh',
      targetPath: HOOK_TARGET_PATH,
    },

    /**
     * task 8.4 (revised): deny an edit anywhere under the store root except
     * the active session worktree, via a PreToolUse hook rather than a
     * permission rule. This emits no `Bash(git …)` deny — see
     * `retiredRules` for why the two that used to live here are gone.
     *
     * A permission rule cannot express that carve-out: Claude Code
     * evaluates deny before allow with no exception mechanism ("a deny rule
     * can't carry allowlist exceptions"), and the default session worktree
     * path is nested INSIDE the store root, so a tree-wide deny would also
     * cover the worktree an allow rule was meant to carve back out — which
     * is exactly the bug this replaces (see proposal.md). A hook resolves
     * the real target path at call time instead, so it has no such gap.
     *
     * `ctxr adapters write-gate` (the hook's target) does the actual
     * decision, reusing `sanctionedPath`'s path resolution via
     * `isWriteInScope` (write-lifecycle/path-gate.ts) so this and the
     * pre-commit path allowlist can never disagree about what counts as an
     * escape.
     */
    render(): Record<string, unknown> {
      return {
        hooks: {
          PreToolUse: [
            {
              matcher: 'Edit|Write|NotebookEdit',
              // Named through Claude Code's project-root placeholder rather
              // than resolved here (reference-the-hook-by-project-dir). The
              // predecessor anchored an absolute path at the main worktree
              // (stabilize-write-gate-hook-path) so it would survive its
              // generating worktree's removal; that fixed staleness but not
              // portability, and this file is committed, so the baked path
              // was wrong on every machine but the last one to generate it.
              //
              // The placeholder cannot go stale: it is expanded against the
              // project the harness actually has open, and the hook script is
              // tracked in git, so it is present in the canonical checkout and
              // in every worktree cut from it. A bare relative path would be
              // equally portable but would resolve against the hook process's
              // working directory, which the harness does not promise is the
              // project root — and a command that fails to resolve fails open.
              hooks: [{ type: 'command', command: `${PROJECT_DIR_PLACEHOLDER}/${HOOK_TARGET_PATH}` }],
            },
          ],
        },
      };
    },

    /**
     * Rules previous releases emitted that `render()` no longer does —
     * reconstructed here (not read back off disk) so `mergeJsonArrayLists`
     * can remove each by exact match, converging a store generated by an
     * earlier version. Two generations are retired here:
     *
     * 1. The Write/Edit deny/allow pair, replaced by the PreToolUse hook
     *    above for the carve-out reason documented on `render()`.
     * 2. `Bash(git push:*)` / `Bash(git commit:*)`. These existed to force
     *    every commit and push through `ctxr session submit`, which ran git
     *    as its own subprocess and so was never matched by a `Bash(git …)`
     *    rule. That command is gone (session-keeps-only-what-git-cannot-do);
     *    `ctxr-submit` now instructs `git commit` and `git push` directly,
     *    which these rules would deny — a config forbidding the very skill
     *    it ships alongside. The guarantee they were credited with is not
     *    lost: the pre-push hook refuses a push to the default branch
     *    whatever runs it, and that hook, not a permission rule, is the
     *    mechanism write-lifecycle actually names.
     */
    retiredRules({ root, worktreesPath }: PermissionConfigInput): Record<string, unknown> {
      const absRoot = root.replace(/^\/+/, '').replace(/\/+$/, '');
      const worktreesSegment = worktreesPath.replace(/^\/+|\/+$/g, '');
      const rootGlob = `//${absRoot}/**`;
      const worktreeGlob = `//${absRoot}/${worktreesSegment}/**`;
      return {
        permissions: {
          deny: [`Write(${rootGlob})`, `Edit(${rootGlob})`, 'Bash(git push:*)', 'Bash(git commit:*)'],
          allow: [`Write(${worktreeGlob})`, `Edit(${worktreeGlob})`],
        },
      };
    },
  },
};
